#include<iostream>
using namespace std;
union DataU {
	int i;
	double d;
	char s[7];
};
//考点：大小端，字节序
int main() {
	DataU du;
	du.s[0] = 255;//11111111
	du.s[1] = 1;  //00000001
	du.s[2] = 0;  //00000000
	du.s[3] = 0;  //00000000
/* 为什么小端序"反着存"？
	CPU 做加减法时，从低位往高位算（就像人做加法从个位开始）。
	小端序把最低位放在地址 0，CPU 读完第一字节就能立刻开始运算，不用先跳到最后找个位。
	打个比方：就像写数字511 ，你习惯从左往右写5 1 1（大端），但做加法时你是从右边的1开始加的。
	小端序就是"存储顺序 = 运算顺序"。
*/
	cout << du.i << endl;//00000000 00000000 00000001 11111111
	du.i = 256;//00000000 00000000 00000001 00000000
	cout << (int )du.s[0] << (int)du.s[1] << (int)du.s[2] << (int)du.s[3] << endl;
	return 0;
}